"""Collects every step's evidence into summary.txt, one place to read the
numbers behind questions 1-9; details stay in the per-step files it names.

Usage: python3 -I summary.py <work> <out dir>
Exits 1 when an input is missing, so a skipped step cannot pass unnoticed.
"""

import json
import os
import sys

work, out = sys.argv[1:3]
fonts = os.path.join(work, "fonts")
missing = []
text = []


def load(path):
    try:
        with open(path, encoding="utf-8") as stream:
            return json.load(stream)
    except FileNotFoundError:
        missing.append(path)
        return None


def w(line=""):
    text.append(line)


def size(name):
    path = os.path.join(fonts, name + ".ttf")
    if not os.path.exists(path):
        missing.append(path)
        return 0
    return os.path.getsize(path)


prep = load(os.path.join(work, "prep.json")) or {}
oracle = load(os.path.join(work, "oracle-check.json")) or {}
metrics = load(os.path.join(out, "eval", "metrics.json")) or {}
compat_txt = os.path.join(out, "compat", "compat.txt")
prior = load(os.path.join(out, "prior-art", "prior-art.json")) or {}
pv = load(os.path.join(out, "pv", "pv.json")) or {}
timing = load(os.path.join(out, "timing.json")) or {}
stats = {n: load(os.path.join(work, "rules", n, "stats.json")) or {} for n in ("char-tw", "char-s", "char-tw-clones")}

w("s2t phrase spike: summary (generated by summary.py; per-step logs in logs/)")
w("=" * 78)

w("\n## Inputs and oracle")
for name, c in sorted(prep.get("corpora", {}).items()):
    if name.endswith((".s", ".t")):
        w(f"  corpus {name:<20} {c['chars']:>7} chars {c['lines']:>5} lines")
w(f"  generated regional phrases (STPhrases_GeneratedFromRegionalPhrases): {prep.get('generated_regional_phrases')}")
w(f"  Homebrew opencc dictionaries equal to the pinned commit: {prep.get('homebrew_dicts_equal_pinned')}")
w(f"  oracle check ok: {oracle.get('ok')}  (text-dict config == stock config; Python emulator == opencc;")
w(f"    OpenCC test cases s2t {oracle.get('testcases', {}).get('s2t')}, s2tw {oracle.get('testcases', {}).get('s2tw')})")

w("\n## Q1/Q2/Q5 rule sets and GSUB cost (glyph space of each character-level font)")
for name, s in stats.items():
    if not s:
        continue
    w(f"  {name}: {s['phrases']} dictionary phrases; kinds {s['kinds']}")
    w(f"    active rules after glyph dedupe {s['active_after_glyph_dedupe']} (conflicts {s['active_glyph_conflicts']}),"
      f" blocking rules: first order {s['blockers_first_order']}, closure {s['blockers_closure']},"
      f" max targets per input glyph {s['max_targets_per_glyph']}")
    w(f"    traditional characters the font lacks (rules dropped/partial): {len(s.get('missing_traditional_chars', {}))}")
    for variant, v in s.get("variants", {}).items():
        w(f"    {variant:<3} rules {v['rules']:>6}  context subtables {v['context_subtables']:>2}  single lookups"
          f" {v['single_lookups']} ({v['single_pairs']} pairs)  GSUB {v['gsub_bytes_before']:>7} -> {v['gsub_bytes_after']:>7} B"
          f"  file {v['file_bytes_before']:>9} -> {v['file_bytes_after']:>9} B (+{v['file_bytes_after'] - v['file_bytes_before']:,})"
          f"  extension lookups {v['extension_lookups']}")
w(f"  alias glyphs (clones.py): char-tw-resaved {size('char-tw-resaved'):,} B -> char-tw-clones {size('char-tw-clones'):,} B"
  f" (+{size('char-tw-clones') - size('char-tw-resaved'):,}); char-tw -> char-tw-clones-R2"
  f" +{size('char-tw-clones-R2') - size('char-tw'):,} B")

w("\n## Q3 accuracy vs the opencc oracle (errors = code points whose glyph is not OpenCC's character)")
corpora = ["sentence", "testcases-s2t", "testcases-s2tw", "nahan", "msr", "pku"]
w(f"  {'oracle':<12}{'font':<19}" + "".join(f"{c:>22}" for c in corpora))
seen = []
for key in metrics:
    if key.count("|") == 3:
        o, c, f, s = key.split("|")
        if (o, f) not in seen:
            seen.append((o, f))
for o, f in seen:
    for shaper in ("hb", "ct"):
        cells = []
        for c in corpora:
            m = metrics.get(f"{o}|{c}|{f}|{shaper}")
            if m is None:
                cells.append(f"{'-':>22}")
                continue
            cells.append(f"{m.get('errors', 0):>6} ({m.get('han_errors', 0):>5}) {m.get('lines_ok', 0):>5}/{m.get('lines', 0):<5}")
        w(f"  {o:<12}{f + ' ' + shaper:<19}" + "".join(f"{x:>22}" for x in cells))
w("  cell = errors (Han-only errors) sentences-ok/sentences; per-line mismatches in eval/mismatches/")
adv = sum(m.get("advance_diffs", 0) for k, m in metrics.items() if k.count("|") == 3)
w(f"  advance differences vs the character-level font, all corpora and shapers: {adv}")
sim = metrics.get("simulator_vs_shaper_differing_lines", {})
w(f"  simulator vs shaper differing lines: total {sum(sim.values())} over {len(sim)} font/corpus/shaper runs;"
  f" examples {metrics.get('simulator_vs_shaper_examples')}")

w("\n## Q4 traditional input through the s2t fonts (code points not shown with their own glyph)")
for key, c in metrics.get("traditional", {}).items():
    if key.endswith("|hb"):
        w(f"  {key[:-3]:<38} chars {c['chars']:>7}  char-level {c['char_level_not_own_glyph']:>5}  phrase font"
          f" {c['phrase_font_not_own_glyph']:>5}  changed by rules {c.get('changed_by_rules', 0):>4}"
          f" (to own glyph {c.get('changed_to_own_glyph', 0)}, away {c.get('changed_away_from_own_glyph', 0)})")
same = all(metrics["traditional"].get(k[:-3] + "|ct") == v for k, v in metrics.get("traditional", {}).items() if k.endswith("|hb"))
w(f"  CoreText identical to HarfBuzz: {same}; rule attribution per occurrence in eval/traditional/")

w("\n## Q5 shaping time (long text, best of 5; other processes can only slow runs down)")
w(f"  text: {timing.get('chars')} chars")
for name, t in timing.get("fonts", {}).items():
    w(f"  {name:<20} hb per pass {t['hb_per_pass_s'] * 1000:7.1f} ms ({t['hb_us_per_char']:.3f} us/char),"
      f" hb start+load {t['hb_start_and_load_s'] * 1000:6.1f} ms, CoreText per pass {t['ct_per_pass_s'] * 1000:7.1f} ms")

w("\n## Q6 feature tag / registration matrix")
if os.path.exists(compat_txt):
    with open(compat_txt, encoding="utf-8") as stream:
        text.extend("  " + line.rstrip("\n") for line in stream)
else:
    missing.append(compat_txt)

w("\n## Q7 prior art (GuanKiapTsingKhai V1.20 -W / -TW)")
for name, p in prior.items():
    big = [l for l in p.get("lookups", []) if l.get("features") == ["ccmp"]]
    w(f"  {name}: {p['file_bytes']:,} B, {p['num_glyphs']} glyphs ({p['glyph_map']['name_not_in_source']} not in the source),"
      f" {p['cmap_code_points']} code points ({p['source_code_points_missing']} of the source's missing), GSUB {p['gsub_bytes']:,} B")
    w(f"    scripts with ccmp: {[s for s, v in p['scripts'].items() if 'ccmp' in v['default']]}; ccmp lookups: "
      + "; ".join(f"type {l['real_type']} via {l['type']}, {l.get('ligatures', l.get('sequences'))} entries,"
                  f" {l['subtables']} subtables" for l in big))
    w(f"    cmap vs ours: {p['cmap_vs_ours']}")

w("\n## Q8 s2t + pseudoVertical")
for k in ("rules", "distinct_target_glyphs", "target_glyph_classes", "rules_hitting_upright_target",
          "nahan_upright_glyph_occurrences_naive", "fixed_turned_glyphs", "fixed_targets_not_turned_after_fix"):
    w(f"  {k}: {pv.get(k)}")
w(f"  upright targets (examples): {''.join(pv.get('upright_target_examples', []))}")
for k in ("sentence_char-level", "sentence_naive", "sentence_fixed"):
    w(f"  {k}: {pv.get(k)}")

if missing:
    w("\nMISSING INPUTS (summary incomplete):")
    for path in missing:
        w(f"  {path}")

with open(os.path.join(out, "summary.txt"), "w", encoding="utf-8") as stream:
    stream.write("\n".join(text) + "\n")
print("\n".join(text))
sys.exit(1 if missing else 0)
